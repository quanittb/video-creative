export function getSampleTextForVoice(voice?: TtsVoice | null, customScript?: string): string {
  if (!voice) {
    return (customScript && customScript.trim()) || SAMPLE_TEXTS_BY_LANG.vi;
  }
  const langCode = (voice.lang || "vi-VN").toLowerCase().split("-")[0];
  const nativeSample = SAMPLE_TEXTS_BY_LANG[langCode] || voice.sampleText || SAMPLE_TEXTS_BY_LANG.vi;

  if (customScript && customScript.trim()) {
    const cleanScript = customScript.trim();
    // Đọc trọn vẹn toàn bộ kịch bản người dùng (giới hạn an toàn tối đa 5000 ký tự)
    return cleanScript.length > 5000 ? cleanScript.substring(0, 5000) : cleanScript;
  }

  return nativeSample;
}

export function getVoiceLanguage(voice?: TtsVoice | null): {
  code: string;
  locale: string;
  name: string;
  isVietnamese: boolean;
  isEnglish: boolean;
} {
  if (!voice) {
    return { code: "vi", locale: "vi-VN", name: "Tiếng Việt", isVietnamese: true, isEnglish: false };
  }
  const locale = voice.lang || "vi-VN";
  const code = locale.split("-")[0].toLowerCase();
  const name = voice.languageName || formatLanguageDisplay(locale);
  return {
    code,
    locale,
    name,
    isVietnamese: code === "vi",
    isEnglish: code === "en",
  };
}

