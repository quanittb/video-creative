export interface TtsVoice {
  id: string;
  voiceId?: string;
  name: string;
  provider: "vieneu" | "edge-tts" | "capcut" | "gemini";
  gender: "male" | "female" | "unknown";
  lang?: string; // e.g. "vi-VN", "en-US", "ja-JP", "fr-FR"
  region: string; // e.g. "Bắc", "Nam", "Hoa Kỳ", "Nhật Bản"
  description: string;
  sampleText: string;
  available?: boolean;
  tags?: string[];
  category?: "news" | "story" | "social" | "natural" | "buddhist" | "tech" | "business";
  language?: string; // alias e.g. "vi", "en", "ja"
  languageName?: string;
}

const langDisplayNames = new Intl.DisplayNames(["vi"], { type: "language" });
const regionDisplayNames = new Intl.DisplayNames(["vi"], { type: "region" });

export function formatLanguageDisplay(langCode: string): string {
  try {
    const [l, ...rest] = langCode.split("-");
    const r = rest.at(-1);
    const lName = langDisplayNames.of(l) ?? l;
    const rName = r ? regionDisplayNames.of(r.toUpperCase()) : null;
    return rName ? `${lName} (${rName})` : lName;
  } catch {
    return langCode;
  }
}

